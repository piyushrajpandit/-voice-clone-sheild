"""
forensics.py - Acoustic measurements and physics-based forensic heuristics.

================================================================================
FORENSIC MEASUREMENT RULES & SCORING HEURISTIC (v2 — TTS-aware):
--------------------------------------------------------------------------------
Synthetic neural vocoders (HiFi-GAN, BigVGAN, WaveGlow) and autoregressive TTS
(ChatGPT, ElevenLabs, Bark) exhibit FOUR distinct acoustic anomaly categories:

1. Pitch Jitter (F0 Micro-Variation):
   - Natural Human: vocal cord biomechanics produce organic micro-tremors.
     F0 jitter_std typically 18–75 Hz.
   - Synthetic TTS: pitch contour is generated by a smoothed ML regression.
     Hyper-flat (std < 12 Hz) OR erratic (std > 110 Hz).
   - Penalty: jitter_penalty = 1.0 if std < 12 or std > 110, else scaled.

2. Spectral Flatness (Noise-to-Tonality Ratio):
   - Natural Human: low flatness < 0.015 (voiced formants dominate).
   - Synthetic AI: vocoder noise floor raises flatness > 0.030.
   - Penalty: flatness_penalty = clamp((flatness - 0.015) / 0.035)

3. Spectral Centroid (Timbre Brightness):
   - Natural: 1,200 – 2,600 Hz.
   - Synthetic: often > 3,200 Hz (high-freq artifacts) or < 900 Hz (truncated).
   - Penalty: centroid_penalty = 1.0 if outside natural range.

4. Energy Envelope Regularity (NEW — catches TTS):
   - Natural Human: RMS energy fluctuates unpredictably across frames.
     Real speech has natural pauses, breath transients, and coarticulation.
     rms_cv (coefficient of variation) is typically > 0.60.
   - Synthetic TTS: energy is generated by a smoothed duration model.
     Unnaturally flat energy envelope: rms_cv < 0.35.
   - Penalty: energy_regularity_penalty = clamp((0.55 - rms_cv) / 0.30)
     (Highest for very flat TTS; zero for naturally variable real speech.)

5. Harmonic-to-Noise Ratio (HNR) Consistency (NEW — catches TTS):
   - Natural Human: ZCR (zero-crossing rate) varies considerably between voiced
     and unvoiced regions. ZCR std / ZCR mean (CV) is typically > 0.55.
   - Synthetic TTS: ZCR is suspiciously consistent across the entire clip
     because voicing transitions are over-smoothed. ZCR_cv < 0.35.
   - Penalty: zcr_regularity_penalty = clamp((0.50 - zcr_cv) / 0.30)

Composite forensics_score (0.0 to 1.0, higher = more synthetic):
   forensics_score = (0.30 * jitter_penalty)
                   + (0.20 * flatness_penalty)
                   + (0.10 * centroid_penalty)
                   + (0.25 * energy_regularity_penalty)
                   + (0.15 * zcr_regularity_penalty)
================================================================================
"""
from typing import Dict, Any
import numpy as np
import librosa


def measure_forensics(audio_array: np.ndarray, sr: int = 16000) -> Dict[str, Any]:
    """
    Extract acoustic forensic features from audio and compute composite AI-likelihood.

    Features measured:
      - pitch_f0_mean: average fundamental frequency (Hz)
      - pitch_jitter_std: frame-to-frame pitch variation (Hz) — low = TTS-like
      - spectral_centroid: brightness center of mass (Hz)
      - spectral_flatness: noise-to-tonality ratio
      - rms_cv: RMS energy coefficient of variation — low = unnaturally steady
      - zcr_cv: zero-crossing rate CV — low = TTS voicing over-smoothed
      - forensics_score: composite 0.0–1.0 (higher = more AI-like)

    Args:
        audio_array: 1D float32 audio samples.
        sr: Sampling rate in Hz (default 16000).

    Returns:
        Dict with all forensic measurements + forensics_score.
    """
    if len(audio_array) == 0:
        return {
            "pitch_f0_mean": 0.0,
            "pitch_jitter_std": 0.0,
            "spectral_centroid": 0.0,
            "spectral_flatness": 0.0,
            "rms_cv": 0.0,
            "zcr_cv": 0.0,
            "forensics_score": 0.0
        }

    audio_data = audio_array.astype(np.float32)
    if audio_data.ndim > 1:
        audio_data = np.mean(audio_data, axis=1)

    try:
        # ── 1. Fundamental Frequency F0 & Pitch Jitter ──────────────────────
        pitches, magnitudes = librosa.piptrack(y=audio_data, sr=sr)
        threshold = np.median(magnitudes) if np.max(magnitudes) > 0 else 0.0
        valid_pitches = pitches[magnitudes > threshold]
        voiced_pitches = valid_pitches[(valid_pitches > 60.0) & (valid_pitches < 500.0)]

        if len(voiced_pitches) > 0:
            pitch_f0_mean  = round(float(np.mean(voiced_pitches)), 2)
            pitch_jitter_std = round(float(np.std(voiced_pitches)), 2)
        else:
            pitch_f0_mean  = 0.0
            pitch_jitter_std = 0.0

        # ── 2. Spectral Centroid ─────────────────────────────────────────────
        centroid = librosa.feature.spectral_centroid(y=audio_data, sr=sr)
        mean_centroid = round(float(np.mean(centroid)), 2)

        # ── 3. Spectral Flatness ─────────────────────────────────────────────
        flatness = librosa.feature.spectral_flatness(y=audio_data)
        mean_flatness = round(float(np.mean(flatness)), 4)

        # ── 4. Energy Envelope Regularity (RMS CV, voiced frames only) ─────
        # TTS has unnaturally flat/steady energy; real speech fluctuates wildly.
        # IMPORTANT: Only measure CV on VOICED frames to avoid silent gaps
        # (long real recordings have silences that otherwise look "regular" = TTS).
        frame_length = 512
        hop_length   = 256
        rms_frames = librosa.feature.rms(
            y=audio_data, frame_length=frame_length, hop_length=hop_length
        )[0]
        # Voice Activity: keep only frames with RMS > 2% of max (skip silences)
        rms_max = float(np.max(rms_frames)) if np.max(rms_frames) > 0 else 1.0
        voiced_rms = rms_frames[rms_frames > 0.02 * rms_max]
        if len(voiced_rms) > 5:
            rms_mean = float(np.mean(voiced_rms))
            rms_cv   = round(float(np.std(voiced_rms) / (rms_mean + 1e-9)), 4)
        else:
            rms_cv = 0.8  # too short to judge — assume natural

        # ── 5. ZCR Regularity (voiced/unvoiced transitions, voiced frames only)
        # TTS voices have suspiciously uniform zero-crossing rate on speech.
        zcr_frames = librosa.feature.zero_crossing_rate(
            y=audio_data, frame_length=frame_length, hop_length=hop_length
        )[0]
        # Align voiced mask to ZCR frame count
        voiced_mask_len = min(len(rms_frames), len(zcr_frames))
        rms_mask = rms_frames[:voiced_mask_len] > 0.02 * rms_max
        voiced_zcr = zcr_frames[:voiced_mask_len][rms_mask]
        if len(voiced_zcr) > 5:
            zcr_mean = float(np.mean(voiced_zcr))
            zcr_cv   = round(float(np.std(voiced_zcr) / (zcr_mean + 1e-9)), 4)
        else:
            zcr_cv = 0.6  # too short to judge — assume natural

        # ── Penalty Calculations ─────────────────────────────────────────────

        # Penalty 1: Pitch Jitter
        if pitch_jitter_std == 0.0:
            jitter_penalty = 0.7
        elif pitch_jitter_std < 12.0 or pitch_jitter_std > 110.0:
            jitter_penalty = 1.0
        else:
            jitter_penalty = max(0.0, (25.0 - pitch_jitter_std) / 25.0)

        # Penalty 2: Spectral Flatness
        flatness_penalty = float(np.clip((mean_flatness - 0.015) / 0.035, 0.0, 1.0))

        # Penalty 3: Spectral Centroid
        if mean_centroid > 3200.0 or (0.0 < mean_centroid < 900.0):
            centroid_penalty = 1.0
        else:
            centroid_penalty = 0.0

        # Penalty 4: Energy Regularity — lower voiced-only rms_cv = TTS
        # On voiced segments: real speech rms_cv > 0.45; TTS rms_cv < 0.25
        # (Softer thresholds now that silence is excluded)
        energy_regularity_penalty = float(np.clip((0.40 - rms_cv) / 0.25, 0.0, 1.0))

        # Penalty 5: ZCR Regularity — lower voiced-only zcr_cv = TTS
        # On voiced segments: real speech zcr_cv > 0.40; TTS zcr_cv < 0.20
        zcr_regularity_penalty = float(np.clip((0.38 - zcr_cv) / 0.25, 0.0, 1.0))

        # ── Composite Score ──────────────────────────────────────────────────
        composite = (
            0.30 * jitter_penalty
          + 0.20 * flatness_penalty
          + 0.10 * centroid_penalty
          + 0.25 * energy_regularity_penalty
          + 0.15 * zcr_regularity_penalty
        )
        forensics_score = round(float(np.clip(composite, 0.0, 1.0)), 4)

        return {
            "pitch_f0_mean":    pitch_f0_mean,
            "pitch_jitter_std": pitch_jitter_std,
            "spectral_centroid": mean_centroid,
            "spectral_flatness": mean_flatness,
            "rms_cv":            rms_cv,
            "zcr_cv":            zcr_cv,
            "forensics_score":   forensics_score
        }

    except Exception as e:
        print(f"Forensics extraction error: {e}")
        return {
            "pitch_f0_mean":    0.0,
            "pitch_jitter_std": 0.0,
            "spectral_centroid": 0.0,
            "spectral_flatness": 0.0,
            "rms_cv":            0.0,
            "zcr_cv":            0.0,
            "forensics_score":   0.5
        }
